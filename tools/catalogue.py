#!/usr/bin/env python3
"""Write the calibration catalogue of an image as Markdown.

    python3 tools/catalogue.py roms/05293190AC.bin docs/catalogue/05293190AC.md

Lists every calibration table found by tools/caltables.py (address, format, size, inputs, where it
is read, name if known), the named constants and the fault table with its P-codes.
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from analyse import Analysis
from gen_source import Calibration, Names, annotation_set
from xref import Xref

FORMAT = {"2D": "2D", "2Dr": "2D (y, x)", "3D": "3D", "3Dn": "3D, no axis", "fault": "fault rows"}


def size_text(d, a, t):
    k = t["kind"]
    if k in ("2D", "2Dr"):
        return "%d points" % d[a]
    if k in ("3D", "3Dn"):
        return "%d x %d%s" % (d[a], d[a + 1], ", signed" if d[a + 2] else "")
    return "%d x %d bytes" % (t["rows"], t["row_size"])


def main():
    path, out = sys.argv[1], sys.argv[2]
    d = open(path, "rb").read()
    an = Analysis(d).run()
    own, ref = annotation_set(d, os.path.splitext(os.path.basename(path))[0])
    names = Names(an, d, own, ref)
    cal = Calibration(d, an, names, own)
    x = Xref(d, an)
    rname = lambda a: names.labels.get(a, "$%05X" % a) if a is not None else ""
    zname = lambda o: names.ram.get(o, "$%04X" % o)
    pn = os.path.splitext(os.path.basename(path))[0]
    L = ["# Calibration catalogue: %s" % pn, "",
         "Generated by `tools/catalogue.py`. Formats and units: [calibration.md](../en/calibration.md)"
         " ([русский](../ru/calibration.md)). Names in the generated form (`Tab3D_0D2B`) are not",
         "identified yet; names marked * are structural (subsystem + inputs, see calibration.md). \"Inputs\" are the values passed to the lookup routine (RAM variables by name",
         "where known, `result of Lookup2D` for a row position from a scale table).", "",
         "%d tables, %d named constants." % (len(cal.items), len(cal.scalars)), "",
         "## Tables", "",
         "| Address | Name | Category | Format | Size | Bytes | Inputs | Result to | Read in | Read at |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for a in sorted(cal.items):
        t = cal.items[a]
        calls = t.get("calls", [])
        owners = []
        for c in calls:
            o = rname(x.owner(c))
            if o not in owners:
                owners.append(o)
        L.append("| $%04X | %s | %s | %s | %s | %d | %s | %s | %s | %s |" % (
            a, t["name"] + ("" if not t.get("cur", {}).get("auto") else " *"), t.get("cur", {}).get("category", ""),
            FORMAT[t["kind"]], size_text(d, a, t), t["size"],
            cal.input_text(t).replace("|", "/") if t.get("inputs") else "",
            ", ".join(zname(o) for o in t.get("dest", {})),
            ", ".join(owners[:3]) + (" +%d" % (len(owners) - 3) if len(owners) > 3 else ""),
            ", ".join("$%05X" % c for c in calls[:4]) + (" +%d" % (len(calls) - 4) if len(calls) > 4 else "")))
    L += ["", "## Named constants", "", "| Address | Name | Value | Description |", "|---|---|---|---|"]
    for a in sorted(cal.scalars):
        v = cal.scalars[a]
        L.append("| $%04X | %s | $%02X (%d) | %s |" % (a, v["name"], d[a], d[a], v.get("desc", "")))
    for a, t in sorted(cal.items.items()):
        if t["kind"] != "fault":
            continue
        L += ["", "## Fault table ($%04X)" % a, "",
              "Rows with a P-code. Columns: row, P-code, blink code, attributes, fault bit (byte offset and",
              "mask in the fault bit array), trigger count.", "",
              "| Row | P-code | Blink | Attributes | Byte | Mask | Count |", "|---|---|---|---|---|---|---|"]
        for r in range(t["rows"]):
            b = d[a + r * t["row_size"]:a + (r + 1) * t["row_size"]]
            if b[6] or b[7]:
                L.append("| %d | P%02X%02X | %02X | $%02X | %d | $%02X | %d |" % (r, b[6], b[7], b[2], b[3], b[5], b[4], b[1]))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w").write("\n".join(L) + "\n")
    print("%s: %d tables, %d constants" % (out, len(cal.items), len(cal.scalars)))


if __name__ == "__main__":
    main()
