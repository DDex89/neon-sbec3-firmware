#!/usr/bin/env python3
"""Generate assembly source for an SBEC3 flash image.

    python3 tools/gen_source.py roms/05293190AC.bin src/05293190AC

Writes one file per 64 KB bank (bank0.asm ...). Code found by tools/analyse.py is written as
instructions, everything else as dc.b. The source assembles back into the identical image with
tools/build.py.
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyse import Analysis
from syntax16 import format_insn

BANK = 0x10000


def label_name(a, an):
    if a == an.vectors()[0][0]:
        return "Reset"
    if a in an.tables:
        return "JumpTable_%05X" % a
    return "L%05X" % a


def generate(image_path, outdir):
    data = open(image_path, "rb").read()
    an = Analysis(data).run()
    # an instruction must not overlap the start of another one; drop such cases to data
    starts = set(an.insn)
    for a, i in list(an.insn.items()):
        if any((a + k) in starts for k in range(1, i.size)):
            an.problems.append(("overlap", a))
    labels = {a: label_name(a, an) for a in an.labels if a < len(data)}

    def lab(a):
        return labels.get(a)

    os.makedirs(outdir, exist_ok=True)
    files = []
    for bank in range(0, len(data), BANK):
        lines = ["; %s, bank %X ($%05X-$%05X)" % (os.path.basename(image_path), bank >> 16, bank,
                                                  min(bank + BANK, len(data)) - 1),
                 "; Generated by tools/gen_source.py.", "",
                 "        org     $%05X" % bank, ""]
        a = bank
        end = min(bank + BANK, len(data))
        while a < end:
            if a in labels:
                lines.append("%s:" % labels[a])
            if a < 0x200 and a % 2 == 0 and a not in an.insn:
                w = (data[a] << 8) | data[a + 1]
                name = labels.get(w) if a >= 2 else None
                if a in (0, 4, 6) or name is None:
                    lines.append("        dc.w    $%04X" % w)
                else:
                    lines.append("        dc.w    %s" % name)
                a += 2
                continue
            ins = an.insn.get(a)
            if ins is not None:
                mn, ops = format_insn(ins, lab)
                lines.append("        %-7s %s" % (mn, ops) if ops else "        %s" % mn)
                a += ins.size
                continue
            run = []
            while a < end and a not in an.insn and len(run) < 16 and not (run and a in labels) \
                    and not (a < 0x200):
                run.append(data[a]); a += 1
            lines.append("        dc.b    " + ",".join("$%02X" % b for b in run))
        name = "bank%X.asm" % (bank >> 16)
        open(os.path.join(outdir, name), "w").write("\n".join(lines) + "\n")
        files.append(name)
    return an, files


def main():
    an, files = generate(sys.argv[1], sys.argv[2])
    cov = sum(i.size for i in an.insn.values())
    print("%d instructions (%d bytes), %d labels, %d jump tables, %d unresolved indirect jumps, "
          "%d problems" % (len(an.insn), cov, len(an.labels), len(an.tables), len(an.indirect),
                           len(an.problems)))
    for p in an.problems[:20]:
        print("  ", p[0], "%05X" % p[1])


if __name__ == "__main__":
    main()
