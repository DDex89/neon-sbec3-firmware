#!/usr/bin/env python3
"""Compare two images of the same family: which tables, constants and code bytes differ.

    python3 tools/caldiff.py roms/05293148AA.bin roms/05007038.bin docs/diffs/05293148AA_05007038.md

Differences are attributed to the calibration tables of the first image (names from its
annotation set), to directly read constants (with the instructions that read them), to code, or
to unreferenced bytes. Tables are printed side by side with the changed cells marked.
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from analyse import Analysis
from gen_source import Calibration, Names, annotation_set
from xref import Xref


def table_cells(d, a, t):
    """(label, offsets) for the parts of a table, for printing."""
    k = t["kind"]
    if k in ("2D", "2Dr"):
        return [("pairs", list(range(a + 2, a + 2 + 2 * d[a])))]
    if k in ("3D", "3Dn"):
        ny, nx = d[a], d[a + 1]
        p = a + 3
        out = []
        if k == "3D":
            out.append(("axis", list(range(p, p + nx))))
            p += nx
        for r in range(ny):
            out.append(("row %d" % r, list(range(p + r * nx, p + (r + 1) * nx))))
        return out
    rs = t["row_size"]
    return [("row %d" % r, list(range(a + r * rs, a + (r + 1) * rs))) for r in range(t["rows"])]


def main():
    pa, pb, out = sys.argv[1:4]
    A, B = open(pa, "rb").read(), open(pb, "rb").read()
    if len(A) != len(B):
        raise SystemExit("images differ in size")
    na, nb = (os.path.splitext(os.path.basename(p))[0] for p in (pa, pb))
    an = Analysis(A).run()
    anb = Analysis(B).run()
    own, ref = annotation_set(A, na)
    names = Names(an, A, own, ref)
    cal = Calibration(A, an, names, own)
    x = Xref(A, an)
    diff = [i for i in range(len(A)) if A[i] != B[i]]
    code_a = set()
    for a, i in an.insn.items():
        code_a.update(range(a, a + i.size))
    code_b = set()
    for a, i in anb.insn.items():
        code_b.update(range(a, a + i.size))
    owner_tab = {}
    for a, t in cal.items.items():
        for k in range(a, a + t["size"]):
            owner_tab[k] = a
    tabs, consts, code, other = {}, {}, [], []
    for i in diff:
        if i in owner_tab:
            tabs.setdefault(owner_tab[i], []).append(i)
        elif i in code_a or i in code_b:
            code.append(i)
        elif i < 0x10000 and i in x.cal:
            consts[i] = x.cal[i]
        else:
            other.append(i)
    L = ["# Calibration differences: %s and %s" % (na, nb), "",
         "Generated by `tools/caldiff.py`. Addresses and names are those of %s; values are shown as"
         " %s -> %s." % (na, na, nb), "",
         "%d bytes differ: %d in %d tables, %d in %d directly read constants, %d in code, %d elsewhere." % (
             len(diff), sum(len(v) for v in tabs.values()), len(tabs), len(consts), len(consts), len(code),
             len(other)), ""]
    if consts:
        L += ["## Constants", "", "| Address | Name | %s | %s | Read by |" % (na, nb), "|---|---|---|---|---|"]
        for i in sorted(consts):
            rd = sorted({names.labels.get(x.owner(a), "$%05X" % (x.owner(a) or 0)) for a, _, _ in consts[i]})
            L.append("| $%04X | %s | $%02X (%d) | $%02X (%d) | %s |" % (
                i, cal.labels.get(i, ""), A[i], A[i], B[i], B[i], ", ".join(rd[:4]) + (" +%d" % (len(rd) - 4) if len(rd) > 4 else "")))
        L.append("")
    if tabs:
        L += ["## Tables", ""]
        for a in sorted(tabs):
            t = cal.items[a]
            ch = set(tabs[a])
            L += ["### $%04X %s (%d bytes changed)" % (a, t["name"], len(ch)), "", "```"]
            for label, offs in table_cells(A, a, t):
                if not any(o in ch for o in offs):
                    continue
                va = " ".join("%3d" % A[o] for o in offs)
                vb = " ".join(("%3d" % B[o]) if o in ch else "  ." for o in offs)
                L.append("%-7s %s" % (label, va))
                L.append("%-7s %s" % ("", vb))
            hdr = [o for o in range(a, a + 3) if o in ch]
            if hdr:
                L.append("header  " + " ".join("$%04X: %d -> %d" % (o, A[o], B[o]) for o in hdr))
            L += ["```", ""]
    if code:
        runs = []
        for i in code:
            if runs and i <= runs[-1][1] + 4:
                runs[-1][1] = i
            else:
                runs.append([i, i])
        L += ["## Code", "", "%d bytes in %d places:" % (len(code), len(runs)), ""]
        for lo, hi in runs[:60]:
            o = x.owner(lo)
            L.append("- $%05X-$%05X in %s" % (lo, hi, names.labels.get(o, "$%05X" % (o or 0))))
        L.append("")
    if other:
        L += ["## Other bytes", "", "Not in a table, not read directly, not code: %s" % ", ".join(
            "$%05X" % i for i in other[:80]) + (" and %d more" % (len(other) - 80) if len(other) > 80 else ""), ""]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w").write("\n".join(L) + "\n")
    print(out, L[4])


if __name__ == "__main__":
    main()
